const DEFAULT_ANSWER = 'مش متأكد من إجابة دقيقة على السؤال ده حاليًا. تقدر تسأل عن: عملة ARA، نقاط الولاء والشارات، الشراء من المتجر، أو ميزات تليجرام. أو تواصل معنا من صفحة "اتصل بنا".';

function normalize(text) {
    return (text || '')
        .toLowerCase()
        .replace(/[أإآ]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي');
}

function findAnswer(message) {
    const normalizedMsg = normalize(message);
    let bestMatch = null;
    let bestScore = 0;

    for (const item of FAQ) {
        for (const kw of item.keywords) {
            const normalizedKw = normalize(kw);
            if (normalizedMsg.includes(normalizedKw)) {
                if (normalizedKw.length > bestScore) {
                    bestScore = normalizedKw.length;
                    bestMatch = item.answer;
                }
            }
        }
    }
    return bestMatch || DEFAULT_ANSWER;
}

module.exports = async function handler(req, res) {
    if (req.method !== 'POST') {
        return res.status(405).json({ error: 'استخدم POST فقط' });
    }

    const { message } = req.body;
    if (!message) {
        return res.status(400).json({ error: 'الرجاء إرسال رسالة' });
    }

    const reply = findAnswer(message);
    return res.status(200).json({ reply });
};
